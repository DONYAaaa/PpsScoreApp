    private static WorkType Fixed(WorkSection s, string num, string title, decimal pts, string? hint = null) =>
        new() { Section = s, Number = num, Title = title, InputKind = ScoreInputKind.Fixed, FixedPoints = pts, Hint = hint };

    private static WorkType Manual(WorkSection s, string num, string title, string? hint = null) =>
        new() { Section = s, Number = num, Title = title, InputKind = ScoreInputKind.Manual, Hint = hint };

    private static WorkType Quantity(WorkSection s, string num, string title, decimal unit, string unitName, string? hint = null) =>
        new() { Section = s, Number = num, Title = title, InputKind = ScoreInputKind.Quantity, UnitPoints = unit, UnitName = unitName, Hint = hint };

    private static WorkType Choice(WorkSection s, string num, string title, (string label, decimal pts)[] options, string? hint = null)
    {
        var wt = new WorkType { Section = s, Number = num, Title = title, InputKind = ScoreInputKind.Choice, Hint = hint };
        int i = 0;
        foreach (var (label, pts) in options)
            wt.Options.Add(new ScoreOption { Label = label, Points = pts, DisplayOrder = i++ });
        return wt;
    }

